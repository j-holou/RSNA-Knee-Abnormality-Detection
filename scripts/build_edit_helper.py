"""Embed the edit and read helpers into the swe-tools skill, so any skill call installs them.

    python scripts/build_edit_helper.py               # v13: .git/sr.py and .git/rd.py, no reading budget
    python scripts/build_edit_helper.py --read-cap 8  # v14: locate, lookup and rd.py share 8 reading calls

Skill scripts run as one copied file inside the task workspace, so each one carries the
helpers' source and writes them to <workspace>/.git/ when it runs (never part of the diff).
install_edit.py does only that, for an agent that has not called another script.
With a read cap, locate.py and lookup.py count as reading calls and refuse once it is used up.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / 'submission/skills/swe-tools/scripts'
HOSTS = ['locate.py', 'lookup.py', 'find_tests.py', 'check_patch.py']
COUNTED = {'locate.py', 'lookup.py'}
START = '# --- sr.py installer (generated by scripts/build_edit_helper.py) ---'
END = '# --- end sr.py installer ---'


def block(read_cap: int, counted: bool) -> str:
    files = {'sr.py': (ROOT / 'scripts/sr_helper.py').read_text(),
             'rd.py': (ROOT / 'scripts/rd_helper.py').read_text(),
             'read_cap': str(read_cap)}
    gate = '''
    if _git is not None and _git.joinpath('rd.py').exists():
        import importlib.util as _u
        _spec = _u.spec_from_file_location('_rd', _git / 'rd.py')
        _rd = _u.module_from_spec(_spec)
        _spec.loader.exec_module(_rd)
        if not _rd.reading_call():
            raise SystemExit(0)
''' if counted and read_cap else ''
    return f'''{START}
def _install_sr():
    import os as _os
    from pathlib import Path as _P
    _git = None
    for cand in (_P('/workspace'), _P(_os.environ.get('PWD', '.')), _P.cwd()):
        if (cand / '.git').is_dir():
            _git = cand / '.git'
            for _name, _text in {files!r}.items():
                try:
                    if _name != 'read_cap' or not (_git / _name).exists():
                        (_git / _name).write_text(_text)
                except OSError:
                    pass
            break{gate}


_install_sr()
{END}
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--read-cap', type=int, default=0)
    a = ap.parse_args()
    for name in HOSTS:
        p = SKILL / name
        s = p.read_text()
        if START in s:
            s = s[:s.index(START)] + s[s.index(END) + len(END) + 1:]
        # insert right before the main guard so it runs on every call
        guard = "if __name__ == '__main__':"
        assert guard in s, name
        s = s.replace(guard, block(a.read_cap, name in COUNTED) + '\n\n' + guard, 1)
        compile(s, name, 'exec')
        p.write_text(s)
    inst = SKILL / 'install_edit.py'
    inst.write_text('"""Installs the edit helper .git/sr.py and the read helper .git/rd.py in the task workspace."""\n\n\n'
                    + block(a.read_cap, False) + "\n\nif __name__ == '__main__':\n    print('Installed .git/sr.py and .git/rd.py. Edit with: cd /workspace && python3 .git/sr.py <file> <<\\'EOF\\' ... EOF')\n")
    compile(inst.read_text(), 'install_edit.py', 'exec')
    print('updated', HOSTS, '+ install_edit.py; read cap', a.read_cap or 'off')


if __name__ == '__main__':
    main()

"""Embed scripts/sr_helper.py into the swe-tools skill so any skill call installs .git/sr.py.

    python scripts/build_edit_helper.py

Skill scripts run as one copied file inside the task workspace, so each one carries the
helper's source and writes it to <workspace>/.git/sr.py when it runs (never part of the
diff). install_edit.py does only that, for an agent that has not called another script.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / 'submission/skills/swe-tools/scripts'
HOSTS = ['locate.py', 'lookup.py', 'find_tests.py', 'check_patch.py']
START = '# --- sr.py installer (generated by scripts/build_edit_helper.py) ---'
END = '# --- end sr.py installer ---'


def block() -> str:
    src = (ROOT / 'scripts/sr_helper.py').read_text()
    return f'''{START}
def _install_sr():
    import os as _os
    from pathlib import Path as _P
    for cand in (_P('/workspace'), _P(_os.environ.get('PWD', '.')), _P.cwd()):
        if (cand / '.git').is_dir():
            try:
                (cand / '.git' / 'sr.py').write_text({src!r})
            except OSError:
                pass
            return


_install_sr()
{END}
'''


def main() -> None:
    b = block()
    for name in HOSTS:
        p = SKILL / name
        s = p.read_text()
        if START in s:
            s = s[:s.index(START)] + s[s.index(END) + len(END) + 1:]
        # insert right before the main guard so it runs on every call
        guard = "if __name__ == '__main__':"
        assert guard in s, name
        s = s.replace(guard, b + '\n\n' + guard, 1)
        compile(s, name, 'exec')
        p.write_text(s)
    inst = SKILL / 'install_edit.py'
    inst.write_text('"""Installs the search/replace edit helper as .git/sr.py in the task workspace."""\n\n\n'
                    + b + "\n\nif __name__ == '__main__':\n    print('Installed .git/sr.py. Edit with: cd /workspace && python3 .git/sr.py <file> <<\\'EOF\\' ... EOF')\n")
    compile(inst.read_text(), 'install_edit.py', 'exec')
    print('updated', HOSTS, '+ install_edit.py')


if __name__ == '__main__':
    main()

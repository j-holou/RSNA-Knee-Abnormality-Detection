"""Build submission/skills/finder-tools/scripts/investigate.py from swe-tools' locate.py and lookup.py.

Skill scripts run as a single copied file inside the task workspace, so they cannot
import siblings. This embeds both scripts' sources and runs them in-process.

    python scripts/build_finder_tool.py [budget]   # default 6 (v12b used 4)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SWE = ROOT / 'submission/skills/swe-tools/scripts'
OUT = ROOT / 'submission/skills/finder-tools/scripts/investigate.py'

TEMPLATE = '''"""The finder's only tool: locate, lookup or read, with a hard budget of __BUDGET__ calls per task.

Generated by scripts/build_finder_tool.py; edit that or swe-tools' scripts, not this file.
The count lives in <workspace>/.git, so it is per task and never shows up in the diff.
Once the budget is used up the script does nothing and tells the finder to write its brief.
"""
import argparse
import contextlib
import io
import os
import sys
from pathlib import Path

BUDGET = __BUDGET__
LOCATE_SRC = __LOCATE__
LOOKUP_SRC = __LOOKUP__
STOP = ('INVESTIGATION BUDGET USED UP. Do not call any tool again. '
        'Reply now with the brief (ISSUE ASKS, FILES, ROOT CAUSE, CHANGE with exact OLD and NEW blocks) from what you have seen.')


def workspace() -> Path:
    for cand in (Path('/workspace'), Path(os.environ.get('PWD', '.')), Path.cwd()):
        if (cand / '.git').exists():
            return cand
    return Path.cwd()


def run_embedded(src: str, argv: list[str]) -> str:
    buf = io.StringIO()
    old = sys.argv
    sys.argv = ['tool'] + argv
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(src, 'tool.py', 'exec'), {'__name__': '__main__'})
    except SystemExit:
        pass
    except Exception as e:  # report instead of crashing the call
        buf.write(f'error: {e!r}')
    finally:
        sys.argv = old
    return buf.getvalue()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--mode', default='lookup')
    ap.add_argument('--query', default='')
    ap.add_argument('--names', default='')
    ap.add_argument('--file', default='')
    ap.add_argument('--start', type=int, default=1)
    ap.add_argument('--end', type=int, default=0)
    a, _ = ap.parse_known_args()
    ws = workspace()
    counter = ws / '.git' / 'finder_calls'
    try:
        used = int(counter.read_text()) if counter.exists() else 0
    except (OSError, ValueError):
        used = 0
    if used >= BUDGET:
        print(STOP)
        return
    try:
        counter.write_text(str(used + 1))
    except OSError:
        pass
    os.chdir(ws)
    mode = a.mode.lower()
    if mode == 'locate':
        out = run_embedded(LOCATE_SRC, ['--query', a.query or a.names])
    elif mode == 'read':
        path = ws / a.file
        lines = path.read_text(encoding='utf-8', errors='replace').splitlines() if path.is_file() else []
        start = max(1, a.start)
        end = min(len(lines), a.end if a.end >= start else start + 79, start + 79)
        out = '\\n'.join(f'{i}: {lines[i - 1]}' for i in range(start, end + 1)) or f'No such file or range: {a.file}'
    else:
        out = run_embedded(LOOKUP_SRC, ['--names', a.names or a.query] + (['--file', a.file] if a.file else []))
    left = BUDGET - used - 1
    print(out.rstrip()[:6000])
    print(f'\\n[{left} investigate call(s) left]' if left else '\\n' + STOP)


if __name__ == '__main__':
    main()
'''


def main() -> None:
    budget = sys.argv[1] if len(sys.argv) > 1 else '6'
    src = TEMPLATE.replace('__BUDGET__', str(int(budget))).replace('__LOCATE__', repr((SWE / 'locate.py').read_text()), 1)
    src = src.replace('__LOOKUP__', repr((SWE / 'lookup.py').read_text()), 1)
    compile(src, str(OUT), 'exec')
    OUT.write_text(src)
    print(OUT, len(src))


if __name__ == '__main__':
    main()
